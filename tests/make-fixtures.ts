// Writes tests/fixtures/tour.json and tests/android/Expected.kt: expected geometry and a scripted run from the TypeScript, for the native checks.
import { readFileSync, writeFileSync } from "node:fs";
import { cardSide, createTour, parseEnabled, parseLessons, ringFor } from "../implementation/web/tour-model.ts";
import type { Rect } from "../implementation/web/tour-model.ts";

const read = (name: string) => readFileSync(new URL(`fixtures/${name}`, import.meta.url), "utf8");
const RECTS: Rect[] = [
  { left: 100, top: 100, right: 200, bottom: 160 }, { left: 100, top: 100, right: 110, bottom: 110 }, { left: -50, top: -50, right: 50, bottom: 50 },
  { left: 500, top: 0, right: 600, bottom: 50 }, { left: 0, top: 900, right: 50, bottom: 950 }, { left: 20, top: 700, right: 380, bottom: 760 },
  { left: 300, top: 400, right: 420, bottom: 500 },
];
const VIEW = { width: 400, height: 800 };

// A scripted run: the actions applied in order and the view after each.
const SCRIPT: [string, string?][] = [["enable"], ["want", "welcome"], ["want", "first-share"], ["want", "welcome"], ["next"], ["screen", "editor"], ["next"], ["skip"], ["want", "editing"], ["screen", "editor"], ["next"], ["next"], ["screen", "home"], ["reset"], ["want", "welcome"]];

export function run() {
  const data = new Map<string, string>();
  const storage = { getItem: (k: string) => data.get(k) ?? null, setItem: (k: string, v: string) => void data.set(k, v), removeItem: (k: string) => void data.delete(k) };
  const tour = createTour({ lessons: parseLessons(read("lessons.json")), storage, translate: (k) => k });
  return SCRIPT.map(([action, arg]) => {
    if (action === "enable") tour.setEnabled(true);
    else if (action === "want") tour.want(arg!);
    else if (action === "next") tour.next();
    else if (action === "skip") tour.skip();
    else if (action === "screen") tour.screenChanged(arg!);
    else if (action === "reset") tour.reset();
    const c = tour.current();
    return { action, arg: arg ?? null, current: c ? `${c.lessonId}:${c.step}:${c.last ? 1 : 0}` : "none", queued: tour.queued(), holding: tour.holding(), seen: ["welcome", "editing", "first-share"].filter((id) => tour.seen(id)) };
  });
}

export function build(): string {
  return JSON.stringify({
    rings: RECTS.map((rect) => { const circle = ringFor(rect, VIEW); return { rect, circle, side: cardSide(circle, VIEW.height) }; }),
    enabled: ["true", "false", "yes", "1", "TRUE", "maybe", ""].map((raw) => ({ raw, value: parseEnabled(raw) })),
    run: run(),
  }, null, 1) + "\n";
}

// The scripted run as Kotlin source rows, so the Android check needs no JSON library.
export function buildKotlin(): string {
  const d = JSON.parse(build());
  const rows = d.run.map((r: any) => `    arrayOf("${r.action}", "${r.arg ?? ""}", "${r.current}", "${r.queued.join(",")}", ${r.holding}, "${r.seen.join(",")}"),`);
  const rings = d.rings.map((r: any) => `    arrayOf(${[r.rect.left, r.rect.top, r.rect.right, r.rect.bottom].map((v: number) => v.toFixed(1)).join(", ")}, ${r.circle ? [r.circle.x, r.circle.y, r.circle.r].join(", ") : "null, null, null"}, "${r.side}"),`);
  return `// Generated by tests/make-fixtures.ts from the TypeScript tour model and tests/fixtures/lessons.json.
// action, argument, current "lesson:step:last", queued, holding, seen
val EXPECTED_RUN = listOf(
${rows.join("\n")}
)
// rect left, top, right, bottom (on a 400 x 800 screen), circle x, y, r (null when off screen), card side
val EXPECTED_RINGS = listOf<Array<Any?>>(
${rings.join("\n")}
)
`;
}

if (import.meta.main) {
  writeFileSync(new URL("fixtures/tour.json", import.meta.url), build());
  writeFileSync(new URL("android/Expected.kt", import.meta.url), buildKotlin());
}
